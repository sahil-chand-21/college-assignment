# Program to check whether a number is even or odd.

given_integer_input = 48

print("Given Number: " + str(given_integer_input))
if given_integer_input % 2 == 0:
    print("The number " + str(given_integer_input) + " is EVEN.")
else:
    print("The number " + str(given_integer_input) + " is ODD.")
