# Program to demonstrate membership operators in and not in.

programming_courses_list = ["Python", "Java", "C++", "Data Structures"]
target_course_one = "Python"
target_course_two = "Ruby"

print("Course List: " + str(programming_courses_list))
print("Is '" + target_course_one + "' in list?     " + str(target_course_one in programming_courses_list))
print("Is '" + target_course_two + "' not in list? " + str(target_course_two not in programming_courses_list))
