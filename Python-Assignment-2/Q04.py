# Program to demonstrate all compound assignment operators.

running_total_value = 50
print("Initial Value:          " + str(running_total_value))

running_total_value += 10
print("After += 10:            " + str(running_total_value))

running_total_value -= 5
print("After -= 5:             " + str(running_total_value))

running_total_value *= 2
print("After *= 2:             " + str(running_total_value))

running_total_value /= 4
print("After /= 4:             " + str(running_total_value))

running_total_value //= 3
print("After //= 3:            " + str(running_total_value))

running_total_value %= 5
print("After %= 5:             " + str(running_total_value))

running_total_value **= 3
print("After **= 3:            " + str(running_total_value))
