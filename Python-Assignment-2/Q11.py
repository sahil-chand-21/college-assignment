# Program to compare two numbers using all relational operators.

comparison_number_one = 25
comparison_number_two = 40

print("Number 1: " + str(comparison_number_one) + ", Number 2: " + str(comparison_number_two))
print("Is Equal (==):             " + str(comparison_number_one == comparison_number_two))
print("Is Not Equal (!=):         " + str(comparison_number_one != comparison_number_two))
print("Is Greater Than (>):       " + str(comparison_number_one > comparison_number_two))
print("Is Less Than (<):          " + str(comparison_number_one < comparison_number_two))
print("Is Greater or Equal (>=):  " + str(comparison_number_one >= comparison_number_two))
print("Is Less or Equal (<=):     " + str(comparison_number_one <= comparison_number_two))
