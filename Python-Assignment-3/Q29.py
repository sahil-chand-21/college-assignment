# Program to calculate the sum and average of all elements in a list.

numerical_marks_list = [80, 75, 90, 85, 70]

total_sum_of_elements = sum(numerical_marks_list)
computed_average_score = total_sum_of_elements / len(numerical_marks_list)

print("List Elements:  " + str(numerical_marks_list))
print("Sum of Values:  " + str(total_sum_of_elements))
print("Average Value:  " + str(computed_average_score))
