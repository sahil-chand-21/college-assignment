# Program to replace a particular word in a sentence using string methods.

base_sentence_content = "Java is the most popular beginner language."
word_to_find = "Java"
replacement_word = "Python"

updated_sentence_content = base_sentence_content.replace(word_to_find, replacement_word)

print("Before Replacement: " + base_sentence_content)
print("After Replacement:  " + updated_sentence_content)
