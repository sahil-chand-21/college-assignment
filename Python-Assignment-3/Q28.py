# Program to find the largest and smallest elements in a list.

numbers_data_set = [45, 12, 89, 7, 63, 98, 24]

largest_element_found = max(numbers_data_set)
smallest_element_found = min(numbers_data_set)

print("List:             " + str(numbers_data_set))
print("Largest Element:  " + str(largest_element_found))
print("Smallest Element: " + str(smallest_element_found))
