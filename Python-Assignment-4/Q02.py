# Program to find the maximum and minimum values from a given collection using built-in functions.

student_test_scores = [78, 92, 65, 88, 99, 54, 83]

highest_score_value = max(student_test_scores)
lowest_score_value = min(student_test_scores)

print("Collection of Scores: " + str(student_test_scores))
print("Maximum Value using max(): " + str(highest_score_value))
print("Minimum Value using min(): " + str(lowest_score_value))
