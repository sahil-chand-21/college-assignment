# Program to demonstrate the use of bin(), oct() and hex() functions.

decimal_integer_value = 85

binary_representation = bin(decimal_integer_value)
octal_representation = oct(decimal_integer_value)
hexadecimal_representation = hex(decimal_integer_value)

print("Decimal Value: " + str(decimal_integer_value))
print("Binary representation using bin(): " + str(binary_representation))
print("Octal representation using oct(): " + str(octal_representation))
print("Hexadecimal representation using hex(): " + str(hexadecimal_representation))
