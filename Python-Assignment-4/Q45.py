# Write a program to demonstrate the use of the from module import * statement.

from math import *

trigonometric_angle = radians(90)
sine_evaluation_result = sin(trigonometric_angle)
logarithm_evaluation_result = log10(1000)

print("Demonstrating 'from math import *':")
print("sin(90 degrees): " + str(sine_evaluation_result))
print("log10(1000):     " + str(logarithm_evaluation_result))
