# Program to demonstrate the use of ceil(), floor() and sqrt() functions.
import math

decimal_sample_number = 8.35
perfect_square_number = 81.0

ceiling_result = math.ceil(decimal_sample_number)
floor_result = math.floor(decimal_sample_number)
square_root_result = math.sqrt(perfect_square_number)

print("Decimal Number: " + str(decimal_sample_number))
print("Ceil using math.ceil(): " + str(ceiling_result))
print("Floor using math.floor(): " + str(floor_result))
print("Square Root using math.sqrt(81.0): " + str(square_root_result))
