# Write a function to add two numbers and display their sum.

def calculate_and_display_sum(first_number, second_number):
    """Calculates and prints the sum of two given numbers."""
    calculated_sum = first_number + second_number
    print("Sum of " + str(first_number) + " and " + str(second_number) + " is: " + str(calculated_sum))

# Function call
calculate_and_display_sum(38, 62)
