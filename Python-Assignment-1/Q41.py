# Program to create variables using different naming conventions and display their values.

# Snake Case (standard Python convention)
student_enrolled_courses = 5

# Camel Case
studentEnrolledCourses = 5

# Pascal Case
StudentEnrolledCourses = 5

# Screaming Snake Case (constants)
MAXIMUM_ALLOWED_COURSES = 8

print("Snake Case (student_enrolled_courses):  ", student_enrolled_courses)
print("Camel Case (studentEnrolledCourses):    ", studentEnrolledCourses)
print("Pascal Case (StudentEnrolledCourses):   ", StudentEnrolledCourses)
print("Constant Case (MAXIMUM_ALLOWED_COURSES):", MAXIMUM_ALLOWED_COURSES)
