# Program to demonstrate the use of type() with string, list, tuple and dictionary variables.

variable_string = "Programming for Problem Solving"
variable_list = ["Lab 1", "Lab 2", "Lab 3"]
variable_tuple = (10, 20, 30)
variable_dictionary = {"semester": 1, "academic_year": 2026}

print(str(variable_string) + " is of type " + str(type(variable_string)))
print(str(variable_list) + " is of type " + str(type(variable_list)))
print(str(variable_tuple) + " is of type " + str(type(variable_tuple)))
print(str(variable_dictionary) + " is of type " + str(type(variable_dictionary)))
