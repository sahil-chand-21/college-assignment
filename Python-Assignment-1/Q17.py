# Program to convert distance from kilometres to metres and centimetres.

distance_in_kilometres = 5.5

distance_in_metres = distance_in_kilometres * 1000.0
distance_in_centimetres = distance_in_metres * 100.0

print("Distance in Kilometres: ", distance_in_kilometres, "km")
print("Distance in Metres:     ", distance_in_metres, "m")
print("Distance in Centimetres:", distance_in_centimetres, "cm")
