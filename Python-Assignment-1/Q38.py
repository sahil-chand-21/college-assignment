# Program to display the length of a string, list, tuple and dictionary using len().

sample_string = "Veer Madho Singh"
sample_list = [10, 20, 30, 40, 50]
sample_tuple = ("North", "South", "East", "West")
sample_dictionary = {"a": 1, "b": 2, "c": 3}

print("Length of String:     ", len(sample_string))
print("Length of List:       ", len(sample_list))
print("Length of Tuple:      ", len(sample_tuple))
print("Length of Dictionary: ", len(sample_dictionary))
