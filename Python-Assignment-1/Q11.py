# Program to calculate the area and perimeter of a rectangle.

rectangle_length = 15.0
rectangle_breadth = 8.0

rectangle_area = rectangle_length * rectangle_breadth
rectangle_perimeter = 2 * (rectangle_length + rectangle_breadth)

print("Rectangle Length:    ", rectangle_length)
print("Rectangle Breadth:   ", rectangle_breadth)
print("Calculated Area:     ", rectangle_area)
print("Calculated Perimeter:", rectangle_perimeter)
