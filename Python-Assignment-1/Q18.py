# Program to calculate the volume of a cube and a cuboid.

cube_side_length = 6.0
cuboid_length = 8.0
cuboid_width = 5.0
cuboid_height = 4.0

volume_of_cube = cube_side_length ** 3
volume_of_cuboid = cuboid_length * cuboid_width * cuboid_height

print("Volume of Cube (Side = 6.0):  ", volume_of_cube)
print("Volume of Cuboid (8 x 5 x 4): ", volume_of_cuboid)
