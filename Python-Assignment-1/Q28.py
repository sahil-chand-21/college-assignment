# Program to demonstrate the use of abs(), round() and pow() functions.

negative_reading = -125.75
absolute_reading = abs(negative_reading)

precise_measurement = 45.6789
rounded_measurement = round(precise_measurement, 2)

base_value = 4
exponent_value = 3
exponential_power_result = pow(base_value, exponent_value)

print("abs(-125.75):      ", absolute_reading)
print("round(45.6789, 2): ", rounded_measurement)
print("pow(4, 3):         ", exponential_power_result)
