# Program to calculate the total and average of five subject marks.

marks_subject_physics = 85.0
marks_subject_chemistry = 78.0
marks_subject_mathematics = 92.0
marks_subject_english = 88.0
marks_subject_computer_science = 95.0

total_obtained_marks = (marks_subject_physics + marks_subject_chemistry +
                        marks_subject_mathematics + marks_subject_english +
                        marks_subject_computer_science)

average_percentage_score = total_obtained_marks / 5.0

print("Total Marks Obtained:", total_obtained_marks, "/ 500")
print("Average Score:       ", average_percentage_score, "%")
